"""Watch the repositories and keep each agent's Dockerfile current.

Every cycle asks GitHub for the head of each private repository and its public copy
(`git ls-remote`, cheap) and only does work when one moved:

  private moved -> fetch, regenerate, and if the output differs commit and push it there; the
                   repository's own sync job then carries it to the public copy
  public moved  -> check the public copy is consistent: its Dockerfile matches its code, and
                   its deployment files match the private repository's. The public copy is a
                   generated mirror, so a direct change there would be lost at the next sync.
                   Mismatches are reported only if they outlast PUBLIC_GRACE_MINUTES (a sync
                   in progress is briefly out of step).
"""

from __future__ import annotations

import difflib
import hashlib
import logging
import time
from pathlib import Path

from .config import Config
from .gitops import Git, GitError
from .notice import Message, Outbox, Section
from . import render as render_module
from .render import NotAnAgent, facts, render
from .state import State

log = logging.getLogger(__name__)

AUTHOR = "Dockerfile agent"
ERROR_AFTER = 3  # consecutive failed cycles before an error is reported (rides out network blips)


class Agent:
    def __init__(self, cfg: Config, git: Git, state: State, outbox: Outbox, clock=time.time):
        self.cfg, self.git, self.state, self.outbox, self.clock = cfg, git, state, outbox, clock
        # A repo is done when its head was processed by this template: a new template (agent
        # upgrade or BASE_IMAGE change) re-renders every repository once.
        source = Path(render_module.__file__).read_bytes() + f"{cfg.base_image} {cfg.timezone}".encode()
        self.template = hashlib.sha256(source).hexdigest()[:12]

    def _done(self, key: str, head: str) -> bool:
        return self.state["heads"].get(key) == f"{head} {self.template}"

    def _mark(self, key: str, head: str) -> None:
        self.state["heads"][key] = f"{head} {self.template}"

    def cycle(self) -> None:
        for repo in self.cfg.repos:
            self._guard(repo, self.update_private, repo)
            if self.cfg.watch_public:
                self._guard(self.cfg.public(repo), self.check_public, repo)
        self._public_alerts()
        self.state.save()

    # --- private: regenerate and commit ---

    def update_private(self, repo: str) -> str | None:
        """Returns the new commit if the Dockerfile was updated."""
        url, key = self.cfg.ssh_url.format(repo=repo), self.cfg.key(repo)
        if self._done(repo, self.git.head(url, self.cfg.branch, key)):
            return None
        path = self._path(repo)
        head = self.git.checkout(url, path, self.cfg.branch, key)
        try:
            files = render(facts(Path(path)), self.cfg.base_image, self.cfg.timezone)
        except NotAnAgent:
            self._mark(repo, head)  # nothing to do until it changes again
            raise
        old = {name: _read(path, name) for name in files}
        changed = sorted(name for name, text in files.items() if old[name] != text)
        new = None
        if changed:
            for name in changed:
                (Path(path) / name).write_text(files[name], encoding="utf-8", newline="\n")
            new = self.git.commit_push(
                path, changed,
                f"Update {' and '.join(changed)}\n\nRegenerated by {AUTHOR.lower()} from the deployment files at "
                f"{head[:12]}.", self.cfg.author_name, self.cfg.author_email, self.cfg.branch, key)
            log.info("%s: committed %s as %s", repo, ", ".join(changed), new[:12])
            self._send(Message(f"🐳 Updated {', '.join(changed)} · {repo.split('/')[1]}", "ok",
                               [Section("", [_diff(old[n], files[n], n)], bullets=False) for n in changed],
                               AUTHOR, f"{repo} @ {new[:7]}"))
        self._mark(repo, new or head)
        return new

    # --- public: check it's consistent ---

    def check_public(self, repo: str) -> None:
        pub = self.cfg.public(repo)
        url = self.cfg.https_url.format(repo=pub)
        if self._done(pub, self.git.head(url, self.cfg.branch)):
            return
        path = self._path(pub)
        head = self.git.checkout(url, path, self.cfg.branch)
        problems = []
        expected = _try_render(path, self.cfg)
        if expected:
            stale = [n for n, text in expected.items() if _read(path, n) != text]
            if stale:
                problems.append(f"{' and '.join(stale)} doesn't match its code.")
            private = _try_render(self._path(repo), self.cfg)
            if private is not None and private != expected:
                problems.append("Its deployment files differ from the private repository's: the sync may have "
                                "failed, or someone changed the public copy directly. Direct changes are overwritten "
                                "by the next sync, so make them in the private repository.")
        self._mark(pub, head)
        entries = self.state["public"]
        if problems:
            prev = entries.get(pub, {})
            entries[pub] = {"since": prev.get("since", self.clock()), "head": head, "problems": problems,
                            "alerted": prev.get("alerted", False)}
        elif pub in entries:
            if entries.pop(pub).get("alerted"):
                self._send(Message(f"✅ {pub.split('/')[1]} is consistent again", "ok", [], AUTHOR, f"{pub} @ {head[:7]}"))

    def _public_alerts(self) -> None:
        for pub, entry in self.state["public"].items():
            if not entry["alerted"] and self.clock() - entry["since"] >= self.cfg.public_grace_minutes * 60:
                if self._send(Message(f"⚠️ {pub.split('/')[1]} is out of step", "warning",
                                      [Section("", entry["problems"])], AUTHOR, f"{pub} @ {entry['head'][:7]}")):
                    entry["alerted"] = True

    # --- plumbing ---

    def _guard(self, target: str, fn, repo: str) -> None:
        errors = self.state["errors"]
        try:
            fn(repo)
        except (GitError, NotAnAgent, OSError, ValueError) as exc:
            log.warning("%s: %s", target, exc)
            prev = errors.get(target, {"count": 0, "notified": False})
            entry = {"msg": str(exc), "count": prev["count"] + 1, "notified": prev["notified"]}
            if entry["count"] >= ERROR_AFTER and (not entry["notified"] or prev.get("msg") != entry["msg"]):
                text = str(exc).replace("`", "'")
                entry["notified"] = self._send(Message(
                    f"❌ {target.split('/')[1]}: can't keep the Dockerfile current", "error",
                    [Section("", [f"```\n{text}\n```", "*Retrying every cycle.*"], bullets=False)], AUTHOR, target))
            errors[target] = entry
            return
        if target in errors and errors.pop(target).get("notified"):
            self._send(Message(f"✅ {target.split('/')[1]} is working again", "ok", [], AUTHOR, target))

    def _path(self, repo: str) -> str:
        return str(Path(self.cfg.work_dir) / repo.replace("/", "__"))

    def _send(self, msg: Message) -> bool:
        log.info("%s\n%s", msg.title, msg.markdown())
        return self.outbox.send(msg)


def _read(path: str, name: str) -> str | None:
    try:
        return (Path(path) / name).read_text(encoding="utf-8")
    except FileNotFoundError:
        return None


def _try_render(path: str, cfg: Config) -> dict[str, str] | None:
    if not (Path(path) / ".git").is_dir():
        return None
    try:
        return render(facts(Path(path)), cfg.base_image, cfg.timezone)
    except NotAnAgent:
        return None


def _diff(old: str | None, new: str, name: str, limit: int = 40) -> str:
    if old is None:
        return f"**{name}** created ({len(new.splitlines())} lines)."
    lines = [l for l in difflib.unified_diff(old.splitlines(), new.splitlines(), lineterm="", n=0)
             if not l.startswith(("---", "+++", "@@"))]
    more = f"\n… {len(lines) - limit} more line(s)" if len(lines) > limit else ""
    body = "\n".join(lines[:limit]).replace("`", "'")
    return f"**{name}**\n```diff\n{body}{more}\n```"
