"""Derive a Dockerfile from how an agent is deployed today.

The LXC deployment is the source of truth, so the container follows it:
  - the systemd unit inside deploy/lxc/*-install: service name, user, module, environment,
    working and state directories
  - deploy/lxc/bootstrap-agent.sh: system packages (minus what only the LXC host needs)
  - requirements.txt: Python dependencies
  - <module>/config.py: ports (*_PORT defaults) and config files under /etc to mount

Rendering is deterministic: the same inputs give byte-identical output, so the agent only
commits when one of those inputs changed something.
"""

from __future__ import annotations

import re
from dataclasses import dataclass, field
from pathlib import Path

# Packages the LXC needs for deploys and its own Python, not the containerised service.
HOST_ONLY = {"python3", "python3-venv", "python3-pip", "rsync", "sudo", "openssh-server"}
GENERATED_BY = "dockerfile-agent"


class NotAnAgent(Exception):
    """The repository has no deploy/lxc/*-install with a systemd unit."""


@dataclass
class Facts:
    name: str
    module: str
    user: str
    group: str
    workdir: str
    env: dict[str, str] = field(default_factory=dict)
    env_file: str = ""
    state_dirs: list[str] = field(default_factory=list)
    packages: list[str] = field(default_factory=list)
    requirements: bool = False
    ports: list[int] = field(default_factory=list)
    mounts: list[str] = field(default_factory=list)
    sources: list[str] = field(default_factory=list)


def facts(root: Path) -> Facts:
    root = Path(root)
    installer, unit = _find_unit(root)
    name = re.search(r"/etc/systemd/system/([\w.@-]+)\.service", installer.read_text(encoding="utf-8"))
    name = name.group(1) if name else installer.name.removesuffix("-install")

    module = re.search(r"\s-m\s+([A-Za-z_]\w*)", unit.get("ExecStart", ""))
    if not module or not (root / module.group(1) / "__main__.py").is_file():
        raise NotAnAgent(f"{installer.relative_to(root).as_posix()}: ExecStart doesn't run a package from this repo")
    module = module.group(1)

    user = unit.get("User", name)
    sources = [installer.relative_to(root).as_posix()]
    f = Facts(name, module, user, unit.get("Group", user), unit.get("WorkingDirectory", f"/opt/{name}/app"))
    for item in _all(unit, "Environment"):
        for pair in item.split():
            k, sep, v = pair.strip('"').partition("=")
            if sep:
                f.env[k] = v
    f.env_file = unit.get("EnvironmentFile", "").lstrip("-")
    f.state_dirs = [f"/var/lib/{d}" for item in _all(unit, "StateDirectory") for d in item.split()]

    bootstrap = root / "deploy" / "lxc" / "bootstrap-agent.sh"
    if bootstrap.is_file():
        sources.append("deploy/lxc/bootstrap-agent.sh")
        pkgs = set()
        for m in re.finditer(r"apt-get install([^\n>|&;]*)", bootstrap.read_text(encoding="utf-8")):
            pkgs |= {p for p in m.group(1).split() if not p.startswith("-")}
        f.packages = sorted(pkgs - HOST_ONLY)

    if (root / "requirements.txt").is_file():
        f.requirements = True
        sources.append("requirements.txt")

    config = root / module / "config.py"
    if config.is_file():
        sources.append(f"{module}/config.py")
        text = config.read_text(encoding="utf-8")
        f.ports = sorted({int(p) for p in re.findall(r"[\"'][A-Z_]*PORT[\"']\s*,\s*(\d+)", text)})
        f.mounts = sorted({p for p in re.findall(r"[\"'](/etc/[^\"'\s]+)[\"']", text) if p != f.env_file})
    f.sources = sources
    return f


def render(f: Facts, base_image: str, timezone: str = "UTC") -> dict[str, str]:
    """The generated files, by path relative to the repository root."""
    return {"Dockerfile": _dockerfile(f, base_image, timezone), ".dockerignore": _dockerignore(f)}


def _dockerfile(f: Facts, base_image: str, timezone: str) -> str:
    run = [f"docker run -d --name {f.name} --restart unless-stopped", "--env-file agent.env"]
    run += [f"-v {f.name}-{'data' if len(f.state_dirs) == 1 else Path(d).name}:{d}" for d in f.state_dirs]
    run += [f"-v /path/to/{Path(m).name}:{m}:ro" for m in f.mounts]
    run += [f"-p {p}:{p}" for p in f.ports]
    run_lines = " \\\n#     ".join(run + [f.name])

    out = [
        f"# Generated by {GENERATED_BY} from: {', '.join(f.sources)}.",
        "# Don't edit by hand: it's regenerated whenever those files change. Change them instead.",
        "#",
        f"# Build: docker build --pull --build-arg PATCHED_AT=$(date +%s) --build-arg REVISION=$(git rev-parse HEAD) -t {f.name} .",
        f"# Run:   {run_lines}",
        "#",
        "# agent.env holds the settings in .env.example (the deploy workflow renders it from repo variables and secrets).",
        "",
        f"FROM {base_image}",
        "",
        "ENV PYTHONDONTWRITEBYTECODE=1 PYTHONUNBUFFERED=1 PIP_NO_CACHE_DIR=1 PIP_DISABLE_PIP_VERSION_CHECK=1",
        f"ENV TZ={timezone}",
        "",
    ]
    # The base OS is fully patched in every build: a new PATCHED_AT (agent-deploy passes the time)
    # changes this layer, so it never comes from cache.
    out += ["ARG DEBIAN_FRONTEND=noninteractive",
            "ARG PATCHED_AT=unknown",
            'RUN echo "Patching the base OS ($PATCHED_AT)" \\',
            " && apt-get update \\",
            " && apt-get -y full-upgrade \\"]
    # tzdata makes TZ work for everything in the image, not just Python.
    packages = sorted(set(f.packages) | {"tzdata"})
    out += [f" && apt-get install -y --no-install-recommends {' '.join(packages)} \\",
            ' && ln -snf "/usr/share/zoneinfo/$TZ" /etc/localtime && echo "$TZ" > /etc/timezone \\',
            " && apt-get clean && rm -rf /var/lib/apt/lists/*", ""]
    home = f.state_dirs[0] if f.state_dirs else f"/var/lib/{f.name}"
    out += [f"RUN groupadd --system {f.group} \\",
            f" && useradd --system --gid {f.group} --home-dir {home} --shell /usr/sbin/nologin {f.user}"
            + "".join(f" \\\n && install -d -o {f.user} -g {f.group} {d}" for d in f.state_dirs), ""]
    out += [f"WORKDIR {f.workdir}"]
    if f.requirements:
        out += ["COPY requirements.txt ./", "RUN pip install -r requirements.txt"]
    out += [f"COPY {f.module}/ ./{f.module}/",
            "ARG REVISION=unknown",
            'RUN echo "$REVISION" > REVISION', ""]
    if f.env:
        out += ["ENV " + " ".join(f"{k}={v}" for k, v in sorted(f.env.items()))]
    out += [f"USER {f.user}"]
    if f.state_dirs:
        out += ["VOLUME [" + ", ".join(f'"{d}"' for d in f.state_dirs) + "]"]
    if f.ports:
        out += ["EXPOSE " + " ".join(str(p) for p in f.ports)]
    out += [f'CMD ["python", "-m", "{f.module}"]', ""]
    return "\n".join(out)


def _dockerignore(f: Facts) -> str:
    keep = (["!requirements.txt"] if f.requirements else []) + [f"!{f.module}/"]
    return "\n".join([f"# Generated by {GENERATED_BY}: only what the image needs.", "*", *keep,
                      "**/__pycache__", "**/*.pyc", ""])


def _find_unit(root: Path) -> tuple[Path, dict[str, str | list[str]]]:
    for installer in sorted((root / "deploy" / "lxc").glob("*-install")):
        text = installer.read_text(encoding="utf-8")
        block = re.search(r"^\[Service\]\n(.*?)(?:^\[|^EOF\b|\Z)", text, re.M | re.S)
        if not block:
            continue
        unit: dict[str, str | list[str]] = {}
        for line in block.group(1).splitlines():
            k, sep, v = line.strip().partition("=")
            if sep and k and not k.startswith("#"):
                unit.setdefault(f"_all:{k}", []).append(v.strip())
                unit[k] = v.strip()
        return installer, unit
    raise NotAnAgent("no deploy/lxc/*-install with a systemd [Service] section")


def _all(unit: dict, key: str) -> list[str]:
    return unit.get(f"_all:{key}", [])
